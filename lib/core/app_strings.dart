  static String get(String lang, String key) {
    final map = lang == 'en' ? _en : _id;
    return map[key] ?? _id[key] ?? key;
  }

  /// Terjemahan memakai bahasa aktif, tanpa perlu `context`.
  /// Bisa dipakai di mana saja: AppStrings.t('save').
  /// Teks yang punya bagian berubah: AppStrings.t('overdue', {'n': 3})
  /// dengan teks 'Lewat {n} hari'.
  static String t(String key, [Map<String, Object>? args]) {
    var text = get(lang, key);
    if (args != null) {
      args.forEach((k, v) => text = text.replaceAll('{$k}', '$v'));
    }
    return text;
  }

